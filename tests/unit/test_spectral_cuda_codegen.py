def test_existing_sources_are_textually_identical():
    actual = {}
    fields = ("hbar", "g_C", "g_R", "g_I", "R", "gamma_C", "gamma_R",
              "gamma_I", "gamma_A", "R_IA", "R_AI", "kappa")
    for precision, model, batched, physics, graph in product(
        ("single", "double"), ("single", "double", "quadratic-double", "nonlinear"),
        (False, True), ((), fields), (False, True),
    ):
        source = kernel_source(precision, model, batched, physics)
        if graph:
            source = source.replace("real scale1, real scale2, real vi_scale,",
                                    "const real* scales, int scale_index, real vi_scale,")
            source = source.replace("scale1", "scales[scale_index]")
            source = source.replace("scale2", "scales[scale_index+1]")
        key = f"split:{precision}:{model}:{int(batched)}:{int(bool(physics))}:{int(graph)}"
        actual[key] = hashlib.sha256(source.encode()).hexdigest()
    for real, model, eta, batched, physics, direct, finish in product(
        ("float", "double"), (0, 1, 2), (0, 1), (False, True),
        ((), ("phase_rate", "gC", "gammaC")), (False, True), (False, True),
    ):
        source = fused_source(real, model, eta, 4, 1 if model == 0 else 2,
                              "k % spatial_n" if batched else "k",
                              "k % pump_n" if batched else "k",
                              "sincosf" if real == "float" else "sincos",
                              physics, direct, finish)
        key = f"ifrk:{real}:{model}:{eta}:{int(batched)}:{int(bool(physics))}:{int(direct)}:{int(finish)}"
        actual[key] = hashlib.sha256(source.encode()).hexdigest()
    assert actual == HASHES


